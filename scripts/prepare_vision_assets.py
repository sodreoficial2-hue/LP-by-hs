#!/usr/bin/env python3
"""Recover unmodified artwork/typefaces from the user's Vision Laiberry 2.1 ZIP/SFX.

No executable is run, no network is used, and no old audio code is copied.
The output is one self-contained JS resource with data URLs, plus provenance.
"""
import argparse
import base64
import hashlib
import json
import re
import zipfile
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("vision_package", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "vision-ui")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    assets, provenance = {}, {}
    with zipfile.ZipFile(args.vision_package) as archive:
        suffix = "resources/app/package.json"
        package = next(n for n in archive.namelist() if n.endswith(suffix))
        prefix = package[:-len("package.json")]
        if json.loads(archive.read(package)).get("version") != "2.1.0":
            raise ValueError("Use o instalador Vision Laiberry 2.1.0; os kits 2.0-dev não são a referência final")

        def resource(key, name, mime):
            raw = archive.read(prefix + "out/" + name)
            assets[key] = "data:" + mime + ";base64," + base64.b64encode(raw).decode("ascii")
            provenance[key] = {"source": name, "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}

        resource("categories", "categories-ref.jpg", "image/jpeg")
        resource("piano", "timbres-ref.jpg", "image/jpeg")
        resource("favorites", "favorites-ref.jpg", "image/jpeg")
        css_name = next(n for n in archive.namelist() if n.startswith(prefix + "out/_next/static/chunks/") and n.endswith(".css"))
        css = archive.read(css_name).decode("utf-8")
        styles = []
        for family in ("DM Sans", "Plus Jakarta Sans"):
            blocks = re.findall(r"@font-face\{[^}]+\}", css)
            block = next(b for b in blocks if "font-family:" + family + ";" in b and "U+??" in b)
            name = re.search(r"src:url\(\.\./media/([^)]*)\)", block).group(1)
            key = family.replace(" ", "")
            resource(key, "_next/static/media/" + name, "font/woff2")
            styles.append("@font-face{font-family:'" + family + "';font-style:normal;font-weight:100 1000;font-display:swap;src:url('" + assets[key] + "') format('woff2')}")
    portrait = root / "recovery/extracted/live/assets/hugo.jpg"
    raw = portrait.read_bytes()
    assets["portrait"] = "data:image/jpeg;base64," + base64.b64encode(raw).decode("ascii")
    provenance["portrait"] = {"source": "LP-by-hs/recovery/extracted/live/assets/hugo.jpg", "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}
    assets["fontCss"] = "\n".join(styles)
    # Font data appear only in fontCss, not twice in the generated bundle.
    for family in ("DM Sans", "Plus Jakarta Sans"):
        del assets[family.replace(" ", "")]
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "assets.js").write_text("/* Original Vision 2.1 assets; generated by prepare_vision_assets.py. */\nwindow.LPVisionAssets=Object.freeze(" + json.dumps(assets, ensure_ascii=True, separators=(",", ":")) + ");\n", encoding="utf-8")
    manifest = {"version": "2.1.0", "package": args.vision_package.name, "package_sha256": hashlib.sha256(args.vision_package.read_bytes()).hexdigest(), "assets": provenance, "changes": "Original bytes, encoded as data URLs. No image or font modification."}
    (args.output / "asset-provenance.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("Vision 2.1: original artwork and fonts recovered locally into", args.output)


if __name__ == "__main__":
    main()
